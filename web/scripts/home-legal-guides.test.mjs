  assert.match(guidesSource, /setTimeout\([\s\S]*?5000\s*\)/)
  assert.match(guidesSource, /onBeforeUnmount/)
  assert.match(guidesSource, /@pointerenter="onPointerEnter"/)
  assert.match(guidesSource, /@pointerleave="onPointerLeave"/)
  assert.match(guidesSource, /@focusin="onFocusIn"/)
  assert.match(guidesSource, /:aria-current="currentIndex === index \? 'page'/)
  assert.match(guidesSource, /@mouseenter="\(\) => showSlide\(index\)"/)
  assert.match(guidesSource, /@focus="\(\) => showSlide\(index\)"/)
  assert.match(guidesSource, /@click="\(\) => showSlide\(index\)"/)
  assert.match(guidesSource, /v-for="\(slide, index\) in slides"/)
  assert.match(guidesSource, /@focusout="onFocusOut"/)
