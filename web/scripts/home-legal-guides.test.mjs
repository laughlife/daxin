test('carousel keeps the empty logistics slide as the reserved third page', () => {
  assert.match(guidesSource, /const slides = computed\(\(\) => \{\s*\/\/ 固定保留三页；国际物流暂未填写时显示预留位置，后台补充后直接使用。\s*return normalizeLegalGuideSlides\(settingValue\('home_legal_guides'\)\)/)
  assert.doesNotMatch(guidesSource, /all\.filter\(slide => Boolean\(slide\.image\)/)
  assert.match(guidesSource, /v-else class="home-legal-guides__reserved"/)
  assert.match(contentSettingsSource, /slug: 'logistics',[\s\S]*?paragraphs: \[\],[\s\S]*?image: ''/)
})

test('admin exposes the same QR selector for all three legal guide slides', () => {
  assert.doesNotMatch(adminSettingsSource, /guide\.slug === 'logistics'/)
  assert.match(adminSettingsSource, /v-for="guide in legalGuides"[\s\S]*?v-model="guide\.qrItemKey"/)
  assert.match(adminSettingsSource, /option\.key === guide\.qrItemKey/)
  assert.match(adminSettingsSource, /qr-tro-public/)
  assert.match(adminSettingsSource, /qr-tro-consult/)
  assert.match(adminSettingsSource, /qr-labor-public/)
  assert.match(adminSettingsSource, /qr-labor-consult/)
  assert.match(adminSettingsSource, /不显示二维码/)
})

test('carousel keeps one shared height by stacking all three slides in the same grid track', () => {
  assert.match(guidesSource, /v-for="\(slide, index\) in slides"[\s\S]*?home-legal-guides__panel/)
  assert.match(guidesSource, /aria-hidden="currentIndex !== index"/)
  assert.match(guidesSource, /home-legal-guides__stage\s*\{[^}]*display:\s*grid/s)
  assert.match(guidesSource, /home-legal-guides__panel\s*\{[^}]*grid-area:\s*1\s*\/\s*1/s)
  assert.doesNotMatch(guidesSource, /<Transition name="home-legal-guides__slide" mode="out-in">/)
})

